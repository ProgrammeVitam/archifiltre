#[tauri::command]
async fn scan_directory(
    app: tauri::AppHandle,
    options: ScanOptions,
) -> Result<CommandResult, String> {
    use tauri_plugin_shell::process::CommandEvent;
    use tauri_plugin_shell::ShellExt;

    let scan_id = options.scan_id.clone();

    // Build CLI arguments
    let mut args = vec![
        "scan".to_string(),
        options.path.clone(),
        "--db".to_string(),
        options.db_name.clone(),
    ];

    if options.include_hidden {
        args.push("--include-hidden".to_string());
    }
    args.push("--batch-size".to_string());
    args.push(options.batch_size.to_string());
    if options.disable_archives {
        args.push("--disable-archives".to_string());
    }

    let sidecar = app
        .shell()
        .sidecar("archifiltre")
        .map_err(|e| format!("Failed to create sidecar: {}", e))?
        .args(&args);

    let (mut rx, _child) = sidecar
        .spawn()
        .map_err(|e| format!("Failed to spawn scan process: {}", e))?;

    let mut full_output = String::new();
    let mut error_output = String::new();
    let mut exit_success = false;

    while let Some(event) = rx.recv().await {
        match event {
            CommandEvent::Stdout(line) => {
                let line_str = String::from_utf8_lossy(&line).to_string();
                full_output.push_str(&line_str);
                full_output.push('\n');
                let _ = app.emit(
                    "scan-progress",
                    ScanProgressEvent {
                        scan_id: scan_id.clone(),
                        line: line_str,
                    },
                );
            }
            CommandEvent::Stderr(line) => {
                let line_str = String::from_utf8_lossy(&line).to_string();
                error_output.push_str(&line_str);
                error_output.push('\n');
                let _ = app.emit(
                    "scan-error",
                    ScanErrorEvent {
                        scan_id: scan_id.clone(),
                        line: line_str,
                    },
                );
            }
            CommandEvent::Terminated(status) => {
                exit_success = status.code == Some(0);
                let _ = app.emit(
                    "scan-complete",
                    ScanCompleteEvent {
                        scan_id: scan_id.clone(),
                        success: exit_success,
                    },
                );
                break;
            }
            _ => {}
        }
    }

    Ok(CommandResult {
        success: exit_success,
        output: full_output,
        error: if exit_success {
            None
        } else {
            Some(error_output)
        },
    })
}

