#[tauri::command]
async fn export_csv(
    app: tauri::AppHandle,
    options: ExportOptions,
) -> Result<CommandResult, String> {
    use std::io::{BufRead, BufReader};
    use std::process::Command;
    use tauri::Manager;

    let mut args = vec!["export".to_string(), options.output_path.clone()];
    if options.full_paths {
        args.push("--full-paths".to_string());
    }
    if let Some(ref db) = options.db_name {
        args.push("--db".to_string());
        args.push(db.clone());
    }

    // Get the sidecar path (same logic as query session)
    let resource_dir = app
        .path()
        .resource_dir()
        .map_err(|e| format!("Failed to get resource dir: {}", e))?;

    let possible_names: Vec<&str> = if cfg!(target_os = "windows") {
        vec!["archifiltre-x86_64-pc-windows-msvc.exe", "archifiltre.exe"]
    } else if cfg!(target_os = "macos") {
        #[cfg(target_arch = "aarch64")]
        let names = vec!["archifiltre-aarch64-apple-darwin", "archifiltre"];
        #[cfg(target_arch = "x86_64")]
        let names = vec!["archifiltre-x86_64-apple-darwin", "archifiltre"];
        #[cfg(not(any(target_arch = "aarch64", target_arch = "x86_64")))]
        let names = vec!["archifiltre-x86_64-apple-darwin", "archifiltre"];
        names
    } else {
        vec!["archifiltre-x86_64-unknown-linux-gnu", "archifiltre"]
    };

    let mut sidecar_path = None;
    for name in &possible_names {
        let path = resource_dir.join(name);
        if path.exists() {
            sidecar_path = Some(path);
            break;
        }
    }

    // Fallback: check next to the executable itself (portable installs)
    if sidecar_path.is_none() {
        let exe_dir = std::env::current_exe()
            .ok()
            .and_then(|p| p.parent().map(|p| p.to_path_buf()));
        if let Some(ref dir) = exe_dir {
            for name in &possible_names {
                let path = dir.join(name);
                if path.exists() {
                    sidecar_path = Some(path);
                    break;
                }
            }
        }
    }

    let binary_path = sidecar_path.ok_or_else(|| {
        format!("Sidecar binary not found. Looked in: {:?}", resource_dir)
    })?;

    // Spawn the process
    let mut child = Command::new(&binary_path)
        .args(&args)
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .map_err(|e| format!("Failed to spawn export process: {}", e))?;

    let stdout = child.stdout.take().ok_or("Failed to get stdout")?;
    let stderr = child.stderr.take().ok_or("Failed to get stderr")?;

    let mut full_output = String::new();
    let mut error_output = String::new();

    // Read stdout
    let stdout_reader = BufReader::new(stdout);
    for line in stdout_reader.lines() {
        if let Ok(line_str) = line {
            full_output.push_str(&line_str);
            full_output.push('\n');
            let _ = app.emit("export-progress", &line_str);
        }
    }

    // Read stderr
    let stderr_reader = BufReader::new(stderr);
    for line in stderr_reader.lines() {
        if let Ok(line_str) = line {
            error_output.push_str(&line_str);
            error_output.push('\n');
            let _ = app.emit("export-error", &line_str);
        }
    }

    // Wait for the process to finish
    let status = child
        .wait()
        .map_err(|e| format!("Failed to wait for process: {}", e))?;
    let _ = app.emit("export-complete", status.success());

    Ok(CommandResult {
        success: error_output.is_empty() && status.success(),
        output: full_output,
        error: if error_output.is_empty() {
            None
        } else {
            Some(error_output)
        },
    })
}

