/// Create a new window
#[tauri::command]
async fn create_window(app: tauri::AppHandle) -> Result<String, String> {
    use tauri::{WebviewUrl, WebviewWindowBuilder};

    // Generate a unique label for the new window
    let window_id = format!("main-{}", uuid::Uuid::new_v4());

    // Create the new window with the same settings as the main window
    let _window = WebviewWindowBuilder::new(&app, &window_id, WebviewUrl::App("index.html".into()))
        .title("Archifiltre")
        .inner_size(1200.0, 800.0)
        .min_inner_size(900.0, 600.0)
        .resizable(true)
        .center()
        .decorations(false)
        .transparent(true)
        .shadow(true)
        .build()
        .map_err(|e| format!("Failed to create window: {}", e))?;

    Ok(window_id)
}

