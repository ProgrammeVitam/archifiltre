/**
 * Tauri API Wrapper
 * Provides typed functions to interact with the Tauri backend commands.
 *
 * Phase 1: Updated for multi-tab support with scan_id routing
 */

import { invoke } from '@tauri-apps/api/core';
import { listen, type UnlistenFn } from '@tauri-apps/api/event';
import { open as openDialog } from '@tauri-apps/plugin-dialog';

// ================================
// Basic Types
// ================================

export interface CommandResult {
	success: boolean;
	output: string;
	error: string | null;
}

export interface ScanOptions {
	/** Unique identifier for this scan (generated by frontend) */
	scanId: string;
	/** Database name for storing scan results (e.g., "tab-{uuid}") */
	dbName: string;
	/** Path to scan */
	path: string;
	includeHidden?: boolean;
	batchSize?: number;
	disableArchives?: boolean;
}

export interface PathValidationResult {
	valid: boolean;
	isDirectory: boolean;
	readable: boolean;
	exists: boolean;
	error?: string;
}

// ================================
// Event Payload Types (with scan_id for routing)
// ================================

export interface ScanProgressEvent {
	scanId: string;
	line: string;
}

export interface ScanErrorEvent {
	scanId: string;
	line: string;
}

export interface ScanCompleteEvent {
	scanId: string;
	success: boolean;
}

// ================================
// Callback Types
// ================================

export type ScanProgressCallback = (event: ScanProgressEvent) => void;
export type ScanErrorCallback = (event: ScanErrorEvent) => void;
export type ScanCompleteCallback = (event: ScanCompleteEvent) => void;

// Legacy callback types (for backwards compatibility during migration)
export type ProgressCallback = (line: string) => void;
export type CompleteCallback = (success: boolean) => void;

// ================================
// Dialog Functions
// ================================

/**
 * Open a folder selection dialog.
 * Returns the selected folder path or null if cancelled.
 */
export async function selectFolder(): Promise<string | null> {
	const result = await openDialog({
		directory: true,
		multiple: false,
		title: 'Select a folder to analyze'
	});
	if (typeof result === 'string') {
		return result;
	}
	return null;
}

// ================================
// Path Validation
// ================================

/**
 * Validate a file system path.
 * Checks if the path exists, is a directory, and is readable.
 */
export async function validatePath(path: string): Promise<PathValidationResult> {
	try {
		return await invoke<PathValidationResult>('validate_path', { path });
	} catch (error) {
		return {
			valid: false,
			isDirectory: false,
			readable: false,
			exists: false,
			error: `Validation failed: ${error}`
		};
	}
}

