// ================================
// Event Listeners - Scan (with scan_id routing)
// ================================

/**
 * Listen for scan progress updates (stdout from CLI).
 * Events include scanId for routing to the correct tab.
 */
export async function onScanProgress(callback: ScanProgressCallback): Promise<UnlistenFn> {
	return await listen<ScanProgressEvent>('scan-progress', (event) => callback(event.payload));
}

/**
 * Listen for scan errors (stderr from CLI).
 * Events include scanId for routing to the correct tab.
 */
export async function onScanError(callback: ScanErrorCallback): Promise<UnlistenFn> {
	return await listen<ScanErrorEvent>('scan-error', (event) => callback(event.payload));
}

/**
 * Listen for scan completion.
 * Events include scanId for routing to the correct tab.
 */
export async function onScanComplete(callback: ScanCompleteCallback): Promise<UnlistenFn> {
	return await listen<ScanCompleteEvent>('scan-complete', (event) => callback(event.payload));
}

